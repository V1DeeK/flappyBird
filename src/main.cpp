// Подключаем заголовочный файл класса Game
// #include - директива препроцессора, которая вставляет содержимое файла Game.hpp в это место
// "Game.hpp" - относительный путь к файлу (в кавычках, значит ищем в текущей директории или в путях компилятора)
#include "Game.hpp"

// int main() - точка входа в программу
// int - функция возвращает целое число (код завершения программы: 0 = успех, не 0 = ошибка)
// main() - специальная функция, с которой начинается выполнение программы
// () - пустые скобки означают, что функция не принимает параметров
int main(){
    // Game game; - создание объекта класса Game на стеке
    // Game - тип (класс), game - имя переменной
    // Вызывается конструктор Game::Game(), который создает окно и инициализирует игру
    Game game;
    
    // game.run(); - вызов метода run() объекта game
    // . - оператор доступа к членам объекта
    // run() - метод, который запускает главный игровой цикл
    // Этот метод будет выполняться до тех пор, пока окно не закроется
    game.run();
    
    // return 0; - возврат значения из функции main
    // 0 означает успешное завершение программы
    // Операционная система получит этот код и поймет, что программа завершилась нормально
    return 0;
}
